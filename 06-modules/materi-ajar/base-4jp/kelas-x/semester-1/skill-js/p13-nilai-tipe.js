// DEFINISI
// nilai = data konkret
// string = teks di dalam kutip
// number = angka untuk hitung
// boolean = true / false
// typeof = mengecek tipe nilai
// ekspresi = kode yang menghasilkan nilai

console.log("=== Literal ===");
console.log("Mimi");
console.log(14);
console.log(true);
console.log(false);

console.log("=== typeof ===");
console.log(typeof "Mimi");
console.log(typeof 14);
console.log(typeof true);
console.log(typeof "14");

console.log("=== Ekspresi & tipe ===");
console.log(10 + 2);
console.log("10" + 2);
console.log("7" + "5");
console.log(7 + 5);
console.log(20 / 4);
console.log(4 * 5);

